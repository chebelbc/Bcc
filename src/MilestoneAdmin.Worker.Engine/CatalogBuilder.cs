using System;
using System.Collections;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Management.Automation;
using System.Management.Automation.Runspaces;
using System.Reflection;
using MilestoneAdmin.Protocol.Json;

namespace MilestoneAdmin.Worker.Engine
{
    /// <summary>
    /// Builds the runtime command catalog (schema 1.0, unclassified) from the installed module using command metadata,
    /// Get-Help and reflection. Mirrors tools/discovery/Export-PSToolsCatalog.ps1. No module command is executed.
    /// </summary>
    public static class CatalogBuilder
    {
        private static readonly HashSet<string> Common = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "Verbose", "Debug", "ErrorAction", "WarningAction", "InformationAction", "ErrorVariable", "WarningVariable",
            "InformationVariable", "OutVariable", "OutBuffer", "PipelineVariable", "WhatIf", "Confirm", "ProgressAction"
        };

        public static JsonObject Build(Runspace runspace, CommandPolicy policy, PSModuleInfo module, EngineOptions options)
        {
            var aliases = new Dictionary<string, List<string>>(StringComparer.OrdinalIgnoreCase);
            foreach (var kv in module.ExportedAliases)
            {
                var target = kv.Value.ResolvedCommand?.Name;
                if (string.IsNullOrEmpty(target)) continue;
                if (!aliases.TryGetValue(target, out var list)) aliases[target] = list = new List<string>();
                list.Add(kv.Key);
            }

            var deprecations = ReadDeprecations(runspace, module);
            var commands = new JsonArray();
            var discrepancies = new JsonArray();
            var documented = 0;
            var all = policy.Commands.Where(c => c is CmdletInfo || c is FunctionInfo).OrderBy(c => c.Name, StringComparer.OrdinalIgnoreCase).ToList();
            foreach (var cmd in all)
            {
                var help = GetHelp(runspace, cmd.Name);
                var c = BuildCommand(cmd, help, aliases, deprecations);
                if (c.GetBool("documented")) documented++;
                commands.Add(c);
            }

            // Mirrors the script: if help is broadly unavailable, "undocumented" does not mean "internal helper".
            var helpBroken = all.Count > 0 && documented < all.Count / 2.0;
            foreach (var c in commands.Select(x => x.AsObject()))
            {
                if (helpBroken) c.Set("internalHelper", false);
                else if (c.GetBool("internalHelper"))
                    discrepancies.Add(new JsonObject { { "command", c.GetString("name") }, { "issue", "Exported but has no help content (possible internal helper)." } });
            }

            if (helpBroken)
                discrepancies.Add(new JsonObject { { "command", "*" }, { "issue", $"Help content was found for only {documented} of {all.Count} commands; internal-helper detection disabled." } });

            var deps = new JsonObject();
            foreach (var kv in deprecations) deps.Set(kv.Key, kv.Value);
            return new JsonObject
            {
                { "schemaVersion", "1.0" },
                { "source", new JsonObject { { "kind", "runtime" }, { "modulePath", module.ModuleBase }, { "note", "Generated by MilestoneAdmin.Worker from the installed module. No MilestonePSTools command was executed." } } },
                { "moduleName", module.Name },
                { "moduleVersion", module.Version.ToString() },
                { "generatedAtUtc", DateTime.UtcNow.ToString("yyyy-MM-ddTHH:mm:ssZ", CultureInfo.InvariantCulture) },
                { "deprecations", deps },
                { "discrepancies", discrepancies },
                { "commands", commands }
            };
        }

        private static Dictionary<string, string> ReadDeprecations(Runspace runspace, PSModuleInfo module)
        {
            var result = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            var path = System.IO.Path.Combine(module.ModuleBase, "deprecations.psd1");
            if (!System.IO.File.Exists(path)) return result;
            try
            {
                using (var ps = PowerShell.Create())
                {
                    ps.Runspace = runspace;
                    ps.AddCommand("Microsoft.PowerShell.Utility\\Import-PowerShellDataFile").AddParameter("Path", path);
                    if (ps.Invoke().FirstOrDefault()?.BaseObject is IDictionary d)
                    {
                        foreach (DictionaryEntry e in d) result[Convert.ToString(e.Key)] = Convert.ToString(e.Value);
                    }
                }
            }
            catch (Exception)
            {
                // Import-PowerShellDataFile may be unavailable; deprecations are informational.
            }

            return result;
        }

        private static PSObject GetHelp(Runspace runspace, string name)
        {
            try
            {
                using (var ps = PowerShell.Create())
                {
                    ps.Runspace = runspace;
                    ps.AddCommand("Microsoft.PowerShell.Core\\Get-Help").AddParameter("Name", name).AddParameter("Full").AddParameter("ErrorAction", ActionPreference.SilentlyContinue);
                    return ps.Invoke().FirstOrDefault();
                }
            }
            catch (Exception)
            {
                return null;
            }
        }

        private static JsonObject BuildCommand(CommandInfo cmd, PSObject help, Dictionary<string, List<string>> aliases, Dictionary<string, string> deprecations)
        {
            var attrs = CommandPolicy.CommandAttributes(cmd).ToList();
            var ssp = false;
            string confirmImpact = null;
            foreach (var a in attrs)
            {
                if (a is CmdletAttribute ca)
                {
                    ssp = ca.SupportsShouldProcess;
                    if (ssp) confirmImpact = ca.ConfirmImpact.ToString();
                }
                else if (a is CmdletBindingAttribute cb)
                {
                    ssp = cb.SupportsShouldProcess;
                    if (ssp) confirmImpact = cb.ConfirmImpact.ToString();
                }
            }

            var synopsis = Text(Prop(help, "Synopsis")).Trim();
            var isDocumented = synopsis.Length > 0 && !synopsis.StartsWith(cmd.Name + " ", StringComparison.OrdinalIgnoreCase) && !string.Equals(synopsis, cmd.Name, StringComparison.OrdinalIgnoreCase);
            var verb = cmd is CmdletInfo ci ? ci.Verb : ((FunctionInfo)cmd).Verb;
            var noun = cmd is CmdletInfo ci2 ? ci2.Noun : ((FunctionInfo)cmd).Noun;
            var o = new JsonObject
            {
                { "name", cmd.Name },
                { "verb", verb },
                { "noun", noun },
                { "commandType", cmd.CommandType.ToString() },
                { "implementation", cmd is CmdletInfo ? "C#" : "PowerShell" },
                { "sourceFile", JsonNull.Instance },
                { "helpUri", Text(Prop(cmd, "HelpUri")) is var uri && uri.Length > 0 ? (JsonNode)uri : JsonNull.Instance },
                { "synopsis", synopsis },
                { "description", Text(Prop(help, "description")) },
                { "documented", isDocumented },
                { "aliases", new JsonArray((aliases.TryGetValue(cmd.Name, out var al) ? al.OrderBy(x => x) : Enumerable.Empty<string>()).Select(x => (JsonNode)x)) },
                { "deprecated", deprecations.ContainsKey(cmd.Name) },
                { "replacedBy", deprecations.TryGetValue(cmd.Name, out var rep) ? (JsonNode)rep : JsonNull.Instance },
                { "internalHelper", !isDocumented },
                { "supportsShouldProcess", ssp },
                { "confirmImpact", confirmImpact },
                { "requirements", Requirements(attrs) },
                { "parameterSets", ParameterSets(cmd) },
                { "parameters", Parameters(cmd, help) },
                { "inputs", new JsonArray() },
                { "outputTypes", new JsonArray(cmd.OutputType.Select(t => (JsonNode)t.Name)) },
                { "examples", Examples(help) }
            };
            return o;
        }

        private static JsonObject Requirements(IEnumerable<object> attrs)
        {
            JsonNode connection = JsonNull.Instance;
            string minVersion = null;
            var features = new SortedSet<string>(StringComparer.Ordinal);
            bool elevation = false, interactive = false, windowsUser = false;
            var documented = new JsonArray();
            foreach (var a in attrs)
            {
                var n = a.GetType().Name;
                switch (n)
                {
                    case "RequiresVmsConnectionAttribute":
                        connection = JsonBool.Of(GetMember<bool>(a, "ConnectionRequired"));
                        break;
                    case "RequiresVmsVersionAttribute":
                        minVersion = MinVersion(GetMember<object>(a, "RequiredVersion"));
                        break;
                    case "RequiresVmsFeatureAttribute":
                        var f = GetMember<string>(a, "Feature");
                        if (!string.IsNullOrEmpty(f)) features.Add(f);
                        break;
                    case "RequiresElevationAttribute":
                        elevation = true;
                        break;
                    case "RequiresInteractiveSessionAttribute":
                        interactive = true;
                        break;
                    case "RequiresVmsWindowsUserAttribute":
                        windowsUser = true;
                        break;
                }

                if (n.StartsWith("Requires", StringComparison.Ordinal))
                {
                    var d = GetMember<string>(a, "Description");
                    if (!string.IsNullOrEmpty(d)) documented.Add(d);
                }
            }

            return new JsonObject
            {
                { "vmsConnection", connection },
                { "minVmsVersion", minVersion },
                { "vmsFeatures", new JsonArray(features.Select(x => (JsonNode)x)) },
                { "elevation", elevation },
                { "interactiveSession", interactive },
                { "windowsUser", windowsUser },
                { "documented", documented }
            };
        }

        private static string MinVersion(object interval)
        {
            if (interval == null) return null;
            var min = GetMember<Version>(interval, "MinVersion");
            return min != null ? min.ToString(2) : Convert.ToString(interval, CultureInfo.InvariantCulture);
        }

        private static T GetMember<T>(object o, string name)
        {
            try
            {
                var t = o.GetType();
                var p = t.GetProperty(name, BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance);
                if (p != null) return (T)p.GetValue(o);
                var f = t.GetField(name, BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance);
                if (f != null) return (T)f.GetValue(o);
            }
            catch (Exception)
            {
                // Attribute shapes can change between module versions; missing data is reported as unknown.
            }

            return default;
        }

        private static JsonArray ParameterSets(CommandInfo cmd)
        {
            var sets = new JsonArray();
            IReadOnlyCollection<CommandParameterSetInfo> psets;
            try
            {
                psets = cmd.ParameterSets;
            }
            catch (Exception)
            {
                return sets;
            }

            foreach (var ps in psets)
            {
                var ps1 = new JsonArray();
                foreach (var p in ps.Parameters)
                {
                    if (Common.Contains(p.Name)) continue;
                    ps1.Add(new JsonObject { { "name", p.Name }, { "mandatory", p.IsMandatory }, { "position", p.Position >= 0 ? (JsonNode)p.Position : JsonNull.Instance } });
                }

                sets.Add(new JsonObject { { "name", ps.Name }, { "isDefault", ps.IsDefault }, { "syntax", cmd.Name + " " + ps }, { "parameters", ps1 } });
            }

            return sets;
        }

        private static JsonArray Parameters(CommandInfo cmd, PSObject help)
        {
            var result = new JsonArray();
            if (cmd.Parameters == null) return result;
            var helpParams = AsList(Prop(Prop(help, "parameters"), "parameter"));
            foreach (var p in cmd.Parameters.Values)
            {
                if (Common.Contains(p.Name)) continue;
                var t = p.ParameterType;
                var element = t.IsArray ? t.GetElementType() : t;
                var accepted = new List<string>();
                var validators = new SortedSet<string>(StringComparer.Ordinal);
                string mipItemType = null, minVms = null, feature = null;
                var validItemTypes = new List<string>();
                foreach (var a in p.Attributes)
                {
                    switch (a)
                    {
                        case ValidateSetAttribute vs:
                            accepted.AddRange(vs.ValidValues);
                            break;
                        default:
                            var n = a.GetType().Name;
                            if (n == "MipItemTransformationAttribute") mipItemType = GetMember<Type>(a, "_type")?.Name;
                            else if (n == "ValidateVmsItemTypeAttribute")
                            {
                                if (GetMember<object>(a, "_itemTypes") is IDictionary d)
                                    foreach (DictionaryEntry e in d) validItemTypes.Add(Convert.ToString(e.Key));
                            }
                            else if (n == "ValidateVmsVersionAttribute") minVms = MinVersion(GetMember<object>(a, "RequiredVersion"));
                            else if (n == "ValidateVmsFeatureAttribute") feature = GetMember<string>(a, "Feature");
                            else if (n.StartsWith("Validate", StringComparison.Ordinal) && n.EndsWith("Attribute", StringComparison.Ordinal) && !(a is ParameterAttribute))
                                validators.Add(n.Substring(0, n.Length - "Attribute".Length));
                            break;
                    }
                }

                if (accepted.Count == 0 && element.IsEnum) accepted.AddRange(Enum.GetNames(element));
                var hp = helpParams.FirstOrDefault(h => string.Equals(Text(Prop(h, "name")), p.Name, StringComparison.OrdinalIgnoreCase));
                var defaultValue = Text(Prop(hp, "defaultValue"));
                var sets = new JsonArray();
                foreach (var kv in p.ParameterSets)
                {
                    sets.Add(new JsonObject
                    {
                        { "set", kv.Key }, { "mandatory", kv.Value.IsMandatory },
                        { "position", kv.Value.Position >= 0 ? (JsonNode)kv.Value.Position : JsonNull.Instance }
                    });
                }

                var o = new JsonObject
                {
                    { "name", p.Name },
                    { "type", ShortName(t) },
                    { "typeFullName", t.FullName },
                    { "description", Text(Prop(hp, "description")) },
                    { "aliases", new JsonArray(p.Aliases.Select(x => (JsonNode)x)) },
                    { "acceptedValues", new JsonArray(accepted.Select(x => (JsonNode)x)) },
                    { "defaultValue", string.IsNullOrEmpty(defaultValue) || defaultValue == "None" ? JsonNull.Instance : (JsonNode)defaultValue },
                    { "acceptsWildcards", string.Equals(Text(Prop(hp, "globbing")), "true", StringComparison.OrdinalIgnoreCase) },
                    { "sets", sets },
                    { "valueFromPipeline", p.ParameterSets.Values.Any(x => x.ValueFromPipeline) },
                    { "valueFromPipelineByPropertyName", p.ParameterSets.Values.Any(x => x.ValueFromPipelineByPropertyName) },
                    { "mandatoryInAnySet", p.ParameterSets.Values.Any(x => x.IsMandatory) }
                };
                if (mipItemType != null) o.Set("mipItemType", mipItemType);
                if (validItemTypes.Count > 0) o.Set("validItemTypes", new JsonArray(validItemTypes.Select(x => (JsonNode)x)));
                if (minVms != null) o.Set("minVmsVersion", minVms);
                if (feature != null) o.Set("vmsFeature", feature);
                if (validators.Count > 0) o.Set("validators", new JsonArray(validators.Select(x => (JsonNode)x)));
                result.Add(o);
            }

            return result;
        }

        private static JsonArray Examples(PSObject help)
        {
            var arr = new JsonArray();
            foreach (var ex in AsList(Prop(Prop(help, "examples"), "example")))
            {
                arr.Add(new JsonObject
                {
                    { "title", Text(Prop(ex, "title")).Trim('-', ' ') },
                    { "code", Text(Prop(ex, "code")) },
                    { "remarks", Text(Prop(ex, "remarks")) }
                });
            }

            return arr;
        }

        public static string ShortName(Type t)
        {
            if (t == null) return "Object";
            if (t.IsArray) return ShortName(t.GetElementType()) + "[]";
            var u = Nullable.GetUnderlyingType(t);
            return u != null ? ShortName(u) : t.Name;
        }

        private static object Prop(object o, string name)
        {
            if (o == null) return null;
            var pso = o as PSObject ?? PSObject.AsPSObject(o);
            try
            {
                return pso.Properties[name]?.Value;
            }
            catch (Exception)
            {
                return null;
            }
        }

        private static List<object> AsList(object o)
        {
            if (o == null) return new List<object>();
            var b = o is PSObject p ? p.BaseObject : o;
            if (b is IEnumerable e && !(b is string)) return e.Cast<object>().ToList();
            return new List<object> { o };
        }

        /// <summary>Help text values are strings, or arrays of objects with a Text property (MAML paragraphs).</summary>
        private static string Text(object o)
        {
            if (o == null) return string.Empty;
            var b = o is PSObject p ? p.BaseObject : o;
            if (b is string s) return s;
            if (b is IEnumerable e)
            {
                var parts = new List<string>();
                foreach (var item in e) parts.Add(Text(Prop(item, "Text") ?? item));
                return string.Join("\n", parts.Where(x => x.Length > 0));
            }

            var t = Prop(o, "Text");
            if (t != null && !ReferenceEquals(t, o)) return Text(t);
            return Convert.ToString(b, CultureInfo.InvariantCulture) ?? string.Empty;
        }
    }
}
