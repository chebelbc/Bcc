"""
Markdown reports generated from a command catalog (static or runtime).

  write_report(catalog, path)               -> command inventory / capability analysis
  write_supported_commands(catalog, support, path) -> SUPPORTED_COMMANDS.md matrix
"""
import collections
import json
import os
import sys

import classification

VERB_GROUPS = collections.OrderedDict([
    ("Read (Get/Find/Test/...)", {"Get", "Find", "Test", "Assert", "Select", "Resolve", "Split", "Join", "Trace", "Wait", "ConvertFrom", "ConvertTo", "Resize"}),
    ("Add / New / Copy", {"Add", "New", "Copy"}),
    ("Set / Update", {"Set", "Update"}),
    ("Remove / Clear", {"Remove", "Clear"}),
    ("Import / Export", {"Import", "Export"}),
])


def _verb_group(verb):
    for g, verbs in VERB_GROUPS.items():
        if verb in verbs:
            return g
    return "Miscellaneous (Connect/Send/Start/Invoke/Move/...)"


def _md_escape(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def write_report(catalog, path):
    cmds = catalog["commands"]
    src = catalog["source"]
    L = []
    w = L.append
    w("# MilestonePSTools Command Inventory & Capability Analysis")
    w("")
    w("> Generated by `tools/catalog/extract_repo_catalog.py` - do not edit by hand.")
    w("")
    w(f"* Source: {src.get('kind')} - {src.get('repository') or ''}")
    if src.get("commit"):
        w(f"* Repository commit: `{src['commit']}` ({src.get('commitDate')})")
    w(f"* Module version: **{catalog.get('moduleVersion')}** (latest released version in the repository changelog"
      f"{', released ' + src['latestReleaseDate'] if src.get('latestReleaseDate') else ''}; `version.json` = {src.get('versionJson')})")
    w(f"* Generated: {catalog['generatedAtUtc']}")
    w("")
    w("This report is derived from the official repository's reference documentation and source code. It is *not* a "
      "substitute for the runtime catalog produced on a Windows machine by `tools/discovery/Export-PSToolsCatalog.ps1`, "
      "which reflects the exact installed module version. The application always uses the runtime catalog when present.")
    w("")
    w("## Totals")
    w("")
    w(f"| Metric | Count |\n|---|---|\n| Total commands | {len(cmds)} |")
    impl = collections.Counter(c.get("implementation") or "unknown" for c in cmds)
    for k, v in sorted(impl.items()):
        w(f"| Implemented in {k} | {v} |")
    w(f"| Deprecated (still exported) | {sum(1 for c in cmds if c['deprecated'])} |")
    w(f"| Support `-WhatIf` / `-Confirm` (SupportsShouldProcess) | {sum(1 for c in cmds if c['supportsShouldProcess'])} |")
    w(f"| Declare `ConfirmImpact = High` | {sum(1 for c in cmds if c.get('confirmImpact') == 'High')} |")
    w(f"| Require a VMS connection (`[RequiresVmsConnection()]`) | {sum(1 for c in cmds if c['requirements'].get('vmsConnection'))} |")
    w(f"| Require a minimum XProtect version | {sum(1 for c in cmds if c['requirements'].get('minVmsVersion'))} |")
    w(f"| Require a licensed VMS feature | {sum(1 for c in cmds if c['requirements'].get('vmsFeatures'))} |")
    w(f"| Require local Administrator elevation | {sum(1 for c in cmds if c['requirements'].get('elevation'))} |")
    w(f"| Require an interactive session | {sum(1 for c in cmds if c['requirements'].get('interactiveSession'))} |")
    w("")
    w("### By verb group")
    w("")
    w("| Group | Count | Commands |\n|---|---|---|")
    groups = collections.OrderedDict((g, []) for g in list(VERB_GROUPS) + ["Miscellaneous (Connect/Send/Start/Invoke/Move/...)"])
    for c in cmds:
        groups[_verb_group(c["verb"])].append(c["name"])
    for g, names in groups.items():
        w(f"| {g} | {len(names)} | {', '.join('`'+n+'`' for n in names)} |")
    w("")
    w("### By risk level")
    w("")
    w("| Risk | Matrix | Count | Meaning |\n|---|---|---|---|")
    rc = collections.Counter(c["risk"]["level"] for c in cmds)
    for r in classification.RULES["riskLevels"]:
        w(f"| {r['id']} | {r['matrix']} | {rc.get(r['id'], 0)} | {r['description']} |")
    w("")
    w("### By category")
    w("")
    w("| Category | Count | Read | Write | Delete |\n|---|---|---|---|---|")
    labels = {c["id"]: c["label"] for c in classification.RULES["categories"]}
    matrix = {r["id"]: r["matrix"] for r in classification.RULES["riskLevels"]}
    byc = collections.OrderedDict()
    for c in sorted(cmds, key=lambda c: c["category"]):
        byc.setdefault(c["category"], []).append(c)
    for cat, cs in byc.items():
        m = collections.Counter(matrix[c["risk"]["level"]] for c in cs)
        w(f"| {labels.get(cat, cat)} | {len(cs)} | {m.get('Read',0)} | {m.get('Write',0)} | {m.get('Delete',0)} |")
    w("")
    w("### GUI suitability")
    w("")
    w("| Level | Count | Meaning |\n|---|---|---|")
    meaning = {
        "AutoForm": "Every mandatory parameter of at least one parameter set maps to a typed control or an XProtect object selector. Can be exposed through the generated form in Command Explorer.",
        "CustomWorkflow": "Needs a purpose-built wizard: destructive/high-impact/sensitive, or mandatory parameters of complex types.",
        "ExpertOnly": "Low-level SDK access, raw service proxies, interactive dialogs or arbitrary method invocation. Shown in Command Explorer as documentation + script preview only.",
        "AppManaged": "Functionality is owned by an application service (connection, site selection, profiles).",
        "NotSuitable": "Deprecated or lacking metadata.",
    }
    gs = collections.Counter(c["guiSuitability"] for c in cmds)
    for k in meaning:
        w(f"| {k} | {gs.get(k,0)} | {meaning[k]} |")
    w("")
    w("## Potentially destructive or high-impact commands")
    w("")
    w("| Command | Risk | WhatIf | ConfirmImpact | Reason |\n|---|---|---|---|---|")
    for c in cmds:
        if c["risk"]["level"] in ("Delete", "HighImpact"):
            w(f"| `{c['name']}` | {c['risk']['level']} | {'Yes' if c['supportsShouldProcess'] else 'No'} | {c.get('confirmImpact') or '-'} | {_md_escape(c['risk']['reason'])} |")
    w("")
    w("## Commands that can return secrets")
    w("")
    w("| Command | Detail |\n|---|---|")
    for c in cmds:
        if c["risk"]["level"] == "Sensitive":
            w(f"| `{c['name']}` | {_md_escape(c['risk']['reason'])} |")
    for name, ps in classification.RULES["sensitiveParameters"].items():
        if name.startswith("$"):
            continue
        w(f"| `{name}` | Only when using: {', '.join('-'+p for p in ps)} |")
    w("")
    w("## WhatIf support (PowerShell ShouldProcess)")
    w("")
    w("Commands that change state **without** declaring `SupportsShouldProcess` cannot be dry-run with `-WhatIf`. "
      "For those the application shows an *application-level validated preview* and labels it as such.")
    w("")
    no_whatif = [c["name"] for c in cmds if not c["supportsShouldProcess"] and classification.RULES["riskLevels"][[r['id'] for r in classification.RULES['riskLevels']].index(c['risk']['level'])]["matrix"] != "Read"]
    yes_whatif = [c["name"] for c in cmds if c["supportsShouldProcess"]]
    w(f"* **With `-WhatIf` ({len(yes_whatif)}):** " + ", ".join(f"`{n}`" for n in yes_whatif))
    w("")
    w(f"* **State-changing without `-WhatIf` ({len(no_whatif)}):** " + ", ".join(f"`{n}`" for n in no_whatif))
    w("")
    w("## Version and feature requirements")
    w("")
    w("| Command | Min XProtect version | Required feature(s) | Elevation | Interactive |\n|---|---|---|---|---|")
    for c in cmds:
        r = c["requirements"]
        if r.get("minVmsVersion") or r.get("vmsFeatures") or r.get("elevation") or r.get("interactiveSession"):
            w(f"| `{c['name']}` | {r.get('minVmsVersion') or '-'} | {', '.join(r.get('vmsFeatures') or []) or '-'} | {'Yes' if r.get('elevation') else '-'} | {'Yes' if r.get('interactiveSession') else '-'} |")
    w("")
    w("Note: `RequiresVmsVersion` values are MilestonePSTools' internal XProtect version numbers (e.g. `21.1` = XProtect 2021 R1).")
    w("")
    w("## Command dependencies (object types)")
    w("")
    w("Which command produces the XProtect objects that other commands need. The application uses this to resolve "
      "objects for the user (e.g. a *Recording Server* picker populated by `Get-VmsRecordingServer`).")
    w("")
    w("| Object type | Producer used by the app | Consumed by (parameter) |\n|---|---|---|")
    consumers = collections.OrderedDict()
    for c in cmds:
        for d in c["dependencies"]["byParameterType"]:
            base = d["type"].replace("[]", "")
            consumers.setdefault(base, []).append(f"`{c['name']}` -{d['parameter']}")
    names = {c["name"] for c in cmds}
    for t in sorted(consumers):
        prod = classification.RULES["objectTypes"][t]["producer"]
        ok = "" if prod in names else " (NOT FOUND in catalog)"
        w(f"| {t} | `{prod}`{ok} | {', '.join(consumers[t][:25])}{' ...' if len(consumers[t]) > 25 else ''} |")
    w("")
    w("## Commands requiring custom workflow design")
    w("")
    w("| Command | Category | Risk | Why |\n|---|---|---|---|")
    for c in cmds:
        if c["guiSuitability"] == "CustomWorkflow":
            w(f"| `{c['name']}` | {labels.get(c['category'], c['category'])} | {c['risk']['level']} | {_md_escape('; '.join(c['guiSuitabilityReasons']))[:300]} |")
    w("")
    w("## Commands suitable for an auto-generated form")
    w("")
    w(", ".join(f"`{c['name']}`" for c in cmds if c["guiSuitability"] == "AutoForm"))
    w("")
    w("## Expert-only and application-managed commands")
    w("")
    w("| Command | Level | Why |\n|---|---|---|")
    for c in cmds:
        if c["guiSuitability"] in ("ExpertOnly", "AppManaged", "NotSuitable"):
            w(f"| `{c['name']}` | {c['guiSuitability']} | {_md_escape('; '.join(c['guiSuitabilityReasons']))} |")
    w("")
    if catalog.get("discrepancies"):
        w("## Documentation / source discrepancies")
        w("")
        w("| Command | Issue |\n|---|---|")
        for d in catalog["discrepancies"]:
            w(f"| `{d['command']}` | {d['issue']} |")
        w("")
    w("## Complete command list")
    w("")
    w("| Command | Category | Risk | WhatIf | Min VMS | Synopsis |\n|---|---|---|---|---|---|")
    for c in cmds:
        w(f"| `{c['name']}`{' *(deprecated)*' if c['deprecated'] else ''} | {labels.get(c['category'], c['category'])} | {c['risk']['level']} | "
          f"{'Yes' if c['supportsShouldProcess'] else '-'} | {c['requirements'].get('minVmsVersion') or '-'} | {_md_escape(c['synopsis'])[:160]} |")
    w("")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L))


def write_supported_commands(catalog, support, path):
    """support: dict loaded from catalog/gui-support.json."""
    cmds = catalog["commands"]
    labels = {c["id"]: c["label"] for c in classification.RULES["categories"]}
    matrix = {r["id"]: r["matrix"] for r in classification.RULES["riskLevels"]}
    wizards = support.get("wizards", {})
    screens = support.get("screens", {})
    L = []
    w = L.append
    w("# Supported Commands")
    w("")
    w("> Generated by `tools/catalog/generate_docs.py` from `catalog/milestonepstools-catalog.json` and "
      "`catalog/gui-support.json`. Do not edit by hand.")
    w("")
    w(f"Validated against MilestonePSTools **{catalog.get('moduleVersion')}** "
      f"(repository commit `{(catalog['source'].get('commit') or '')[:12]}`). The *PSTools Version* column is the minimum "
      "module version in which the application has verified the command; it is the catalog version unless noted. "
      "The installed version on each workstation is re-checked at runtime and any command missing from it is disabled in the UI.")
    w("")
    w("Columns:")
    w("")
    w("* **GUI Supported** - `Yes`: reachable through a dedicated screen or wizard; `Form`: reachable through the "
      "generated form in Command Explorer (Expert Mode); `Docs`: listed in Command Explorer with documentation and script "
      "preview only; `No`: not exposed.")
    w("* **Wizard** - name of the guided workflow, if any.")
    w("* **Risk** - Read / Write / Delete, followed by the detailed risk level used for confirmations.")
    w("")
    totals = collections.Counter()
    rows = []
    for c in cmds:
        n = c["name"]
        if n in wizards or n in screens:
            gui = "Yes"
        elif c["guiSuitability"] == "AutoForm":
            gui = "Form"
        elif c["guiSuitability"] in ("ExpertOnly", "CustomWorkflow"):
            gui = "Docs"
        elif c["guiSuitability"] == "AppManaged":
            gui = "Yes" if n in support.get("appManagedImplemented", []) else "No"
        else:
            gui = "No"
        totals[gui] += 1
        wiz = ", ".join(wizards.get(n, [])) or "-"
        rows.append(f"| `{n}` | {catalog.get('moduleVersion')} | {gui} | {wiz} | {matrix[c['risk']['level']]} ({c['risk']['level']}) | {labels.get(c['category'], c['category'])} |")
    w("Summary: " + ", ".join(f"{k}: {v}" for k, v in sorted(totals.items())))
    w("")
    w("| Command | PSTools Version | GUI Supported | Wizard | Risk | Category |\n|---|---|---|---|---|---|")
    L.extend(rows)
    w("")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L))


if __name__ == "__main__":
    cat = json.load(open(sys.argv[1], encoding="utf-8"))
    write_report(cat, sys.argv[2])
