#!/usr/bin/env python3
"""
Generates C# stand-ins for what the WPF markup compiler produces from XAML (InitializeComponent and x:Name fields), so
the UI's C# code can be compiled against the real .NET Framework 4.8 WPF reference assemblies on machines without the
WPF build tasks (e.g. Linux CI). The real Windows build uses the genuine markup compiler; this is verification only.

Usage: python3 generate_xaml_stubs.py <ui-project-dir> <output.cs>
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

WPF = "http://schemas.microsoft.com/winfx/2006/xaml/presentation"
X = "http://schemas.microsoft.com/winfx/2006/xaml"

# Element tag -> CLR type for x:Name fields (only controls used with x:Name in this project need to be listed).
TYPE_MAP = {
    "TextBox": "System.Windows.Controls.TextBox",
    "TextBlock": "System.Windows.Controls.TextBlock",
    "Button": "System.Windows.Controls.Button",
    "DataGrid": "System.Windows.Controls.DataGrid",
    "ListBox": "System.Windows.Controls.ListBox",
    "PasswordBox": "System.Windows.Controls.PasswordBox",
    "ComboBox": "System.Windows.Controls.ComboBox",
    "Grid": "System.Windows.Controls.Grid",
    "StackPanel": "System.Windows.Controls.StackPanel",
    "Border": "System.Windows.Controls.Border",
}


def main(project, out):
    lines = ["// <auto-generated> Verification stubs for XAML-generated members. Not used by the Windows build. </auto-generated>",
             "#pragma warning disable CS0649, CS0169, CS0414"]
    for dirpath, _, files in os.walk(project):
        if os.sep + "obj" in dirpath or os.sep + "bin" in dirpath:
            continue
        for fn in sorted(files):
            if not fn.endswith(".xaml"):
                continue
            path = os.path.join(dirpath, fn)
            root = ET.parse(path).getroot()
            cls = root.get("{%s}Class" % X)
            if not cls:
                continue
            ns, _, name = cls.rpartition(".")
            fields = []
            for el in root.iter():
                n = el.get("{%s}Name" % X)
                if not n:
                    continue
                tag = el.tag.split("}")[-1]
                if tag not in TYPE_MAP:
                    raise SystemExit(f"{path}: add a type mapping for x:Name element <{tag}>")
                fields.append((TYPE_MAP[tag], n))
            lines.append(f"namespace {ns}")
            lines.append("{")
            lines.append(f"    partial class {name}")
            lines.append("    {")
            for t, n in fields:
                lines.append(f"        internal {t} {n};")
            lines.append("        public void InitializeComponent() { }")
            lines.append("    }")
            lines.append("}")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote XAML stubs to {out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
